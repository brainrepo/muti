const dict = { it, en }
export type T = (key: Key) => string

export const LangContext = createContext<Lang>('it')
export const useLang = () => useContext(LangContext)
export function useT(): T {
  const lang = useContext(LangContext)
  return (key) => dict[lang][key]
}

